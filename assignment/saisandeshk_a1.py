def load_blacklist_categories():
    """
    Reads domains from the blacklist directory structure.
    Returns a set of domains for fast lookup.
    """
    print("Loading blacklist categories...")
    blacklisted_domains = set()

    ## start your edits here  =================

    # use os.walk() to visit every sub-folder beneath the BLACKLIST_DOMIAINS_DIR recursively:
    for dirpath, dirnames, filenames in os.walk(BLACKLIST_DOMAINS_DIR):
      for filename in filenames:
        if filename not in ('domains', 'url'): # only process files named 'domains' or 'urls' and ignore any other files present
          continue

        filepath = os.path.join(dirpath, filename)
        with open(filepath, 'r', errors='ignore') as f:
          for line in f:
            line = line.strip() # remove leading / trailing whitespace and newlines

            if not line or line.startswith('#'):
              continue # skip blank lines and comment lines

            blacklisted_domains.add(line)

    ## end your edits here  =================

    return blacklisted_domains

def step_2_ingestion():
    """
    Load parquet files and filter out blacklisted domains.
    Returns DataFrame with columns: warc_id, url, date, html_content
    """

    blacklisted_domains = load_blacklist_categories()

    ## start your edits here  =================

    # broadcast the blacklist set to all the spark workers and with broadcast(), each worker receives one efficient cached copy in memory.
    broadcast_blacklist = spark.sparkContext.broadcast(blacklisted_domains)

    def is_blacklisted(domain) -> bool:
    # returns True if domain exactly matches or is a subdomain of any entry in the broadcast blacklist set.

      if not domain:
        return False

      # access the broadcasted set on 'this' worker via .value
      bl = broadcast_blacklist.value

      if domain in bl: # domain check
        return True

      # sub-domain check
      parts = domain.split('.')
      for i in range(1, len(parts)-1):
        parent = '.'.join(parts[i:])
        if parent in bl:
          return True

      return False

    # register as a spark UDF returning boolean. (True = Blacklisted = Drop)
    is_blacklisted_udf = F.udf(is_blacklisted, BooleanType())

    # load parquet written in step-1
    df = spark.read.parquet(PARQUET_DIR)

    # extract hostname from URL
    df = df.withColumn(
        'domain',
        F.regexp_extract(F.col('url'), r'https?://([^/?\s]+)', 1)
    )

    # filter out the blacklisted domains and due to boolen logic, we keep rows where is_blacklisted returns False
    df_filtered = df.filter(~is_blacklisted_udf(F.col('domain')))

    output_df = df_filtered.drop('domain') # drop the 'domain' as per schema

    ## end your edits here  =================

    return output_df

