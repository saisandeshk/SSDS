def step_5a_deduplication(input_df):
    """
    Args:
        input_df: English text dataframe.
    Returns:
        DataFrame: Deduplicated dataframe using MinHash LSH.
    """
    ## start your edits here  =================

    def char_ngrams(text):
      if not text:
          return []
      return list(set(text[i:i+5] for i in range(len(text) - 4)))

    char_ngrams_udf = F.udf(char_ngrams, ArrayType(StringType()))

    def extract_bands(hashes):
      if not hashes or len(hashes) != 24:
          return []
      return [f"{i}_{int(hashes[i*3][0])}_{int(hashes[i*3+1][0])}_{int(hashes[i*3+2][0])}" for i in range(8)]

    extract_bands_udf = F.udf(extract_bands, ArrayType(StringType()))

    def get_indices(vec):
      return vec.indices.tolist() if vec else []

    get_indices_udf = F.udf(get_indices, ArrayType(IntegerType()))

    # feature extraction: char 5-grams -> hashing TF -> minhash signatures
    df = input_df.withColumn("ngrams", char_ngrams_udf(F.col("extracted_text"))).withColumn("text_len", F.length(F.col("extracted_text")))
    df = HashingTF(inputCol="ngrams", outputCol="features", numFeatures=2**18).transform(df)
    mh_model = MinHashLSH(inputCol="features", outputCol="hashes", numHashTables=24).fit(df)
    df = mh_model.transform(df)
    df.cache().count()

    # lightweight view with band keys and feature indices
    lite = df.select(
        F.col("warc_id").alias("w_id"),
        F.col("text_len").alias("t_len"),
        extract_bands("hashes").alias("bands"),
        get_indices("features").alias("indices")
    )

    # candidate generation via band matching
    exploded = lite.select("w_id", F.explode("bands").alias("band"))
    candidates = exploded.alias("a") \
        .join(exploded.alias("b"), F.col("a.band") == F.col("b.band")) \
        .filter(F.col("a.w_id") < F.col("b.w_id")) \
        .select(F.col("a.w_id").alias("id1"), F.col("b.w_id").alias("id2")) \
        .distinct()

    # exact jaccard distance on candidate pairs
    pairs = candidates \
        .join(lite.alias("d1"), F.col("id1") == F.col("d1.w_id")) \
        .select("id1", "id2", F.col("d1.indices").alias("ind1"), F.col("d1.t_len").alias("len1")) \
        .join(lite.alias("d2"), F.col("id2") == F.col("d2.w_id")) \
        .select("id1", "id2", "ind1", "len1", F.col("d2.indices").alias("ind2"), F.col("d2.t_len").alias("len2"))

    dupes = pairs \
        .withColumn("inter", F.size(F.array_intersect("ind1", "ind2"))) \
        .withColumn("union_sz", F.size("ind1") + F.size("ind2") - F.col("inter")) \
        .withColumn("jdist", 1.0 - F.col("inter") / F.col("union_sz")) \
        .filter(F.col("jdist") <= 0.5)

    # drop the shorter doc from each duplicate pair
    losers = dupes.select(
        F.when(F.col("len1") >= F.col("len2"), F.col("id2"))
        .otherwise(F.col("id1")).alias("warc_id")
    ).distinct()

    output_df = input_df.join(losers, on="warc_id", how="left_anti")
    df.unpersist()

    ## end your edits here  =================

    return output_df

