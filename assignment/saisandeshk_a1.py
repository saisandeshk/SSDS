def step_1_warc_to_parquet():
    """
    Convert warc files at BASE_DIR and place the parquet file in PARQUET_DIR
    """
    ## start your edits here  =================

    # define schema
    schema = StructType([
        StructField("warc_id", StringType(), nullable=True),
        StructField("url", StringType(), nullable=True),
        StructField("date", StringType(), nullable=True),
        StructField("html_content", StringType(), nullable=True),
        StructField("warc_filename", StringType(), nullable=True)
    ])

    warc_paths = [os.path.join(BASE_DIR, f) for f in os.listdir(BASE_DIR) if f.endswith('.warc')]

    def parse_warc_file(filepath):
      # generator that streams one WARC file and yeilds one tuple per valid HTML response record
      filename = os.path.basename(filepath)

      with open(filepath, "rb") as f:
        # streams record by record
        for record in ArchiveIterator(f):

          if record.rec_type != 'response':
            continue

          content_type = record.http_headers.get_header('Content-Type') or ''
          if 'html' not in content_type.lower():
            continue

          html_content = record.content_stream().read().decode(
              'utf-8', errors='replace'
          )

          # YIELD (not append + return): Spark pulls this one record, then immediately asks for the next - memory is freed between yields
          yield (
              record.rec_headers.get_header('WARC-RECORD-ID'),
              record.rec_headers.get_header('WARC-Target-URI'),
              record.rec_headers.get_header('WARC-Date'),
              html_content,
              filename,
          )

    rdd = spark.sparkContext.parallelize(warc_paths, numSlices=len(warc_paths))

    records_rdd = rdd.flatMap(parse_warc_file)

    df = spark.createDataFrame(records_rdd, schema=schema)

    df.write.partitionBy('warc_filename').parquet(PARQUET_DIR, mode='overwrite')

    ## end your edits here  =================


